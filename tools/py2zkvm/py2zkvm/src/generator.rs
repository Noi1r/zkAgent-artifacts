use crate::parser::{self, RustFunction};
use anyhow::{Context, Result};
use quote::format_ident;

pub struct Sp1Config {
    pub main_function: RustFunction,
    pub all_functions: Vec<RustFunction>,
    pub rust_code: String,
    pub precompiles: bool,
}

pub fn generate_guest_code(config: &Sp1Config) -> Result<String> {
    let main_fn = &config.main_function;
    let cleaned = crate::transpiler::clean_for_zkvm(&config.rust_code)?;
    let mut file = syn::parse_file(&cleaned)?;
    let mut entry_name = "__py2zkvm_entrypoint".to_string();
    while cleaned.contains(&entry_name) {
        entry_name.push('_');
    }
    let entry = format_ident!("{}", entry_name);
    let selected: syn::Ident = syn::parse_str(&main_fn.name)?;
    let mut input_reads: Vec<syn::Stmt> = Vec::new();
    let mut arguments: Vec<syn::Expr> = Vec::new();
    for (name, typ) in &main_fn.params {
        let name: syn::Ident = syn::parse_str(name)?;
        let parameter: syn::Type = syn::parse_str(typ)?;
        let owned_type = parser::input_type_for_zkvm(typ)
            .with_context(|| format!("Unsupported input type for {name}"))?;
        let mutable = matches!(&parameter, syn::Type::Reference(r) if r.mutability.is_some());
        if mutable {
            input_reads
                .push(syn::parse_quote! { let mut #name: #owned_type = sp1_zkvm::io::read(); });
        } else {
            input_reads.push(syn::parse_quote! { let #name: #owned_type = sp1_zkvm::io::read(); });
        }
        arguments.push(match parameter {
            syn::Type::Reference(r) if r.mutability.is_some() => syn::parse_quote!(&mut #name),
            syn::Type::Reference(_) => syn::parse_quote!(&#name),
            _ => syn::parse_quote!(#name),
        });
    }
    let call = syn::parse_quote!(#selected(#(#arguments),*));
    let (_, computation) = parser::adapt_output(&main_fn.return_type, call)?;
    file.shebang = None;
    file.attrs
        .retain(|attribute| !attribute.path().is_ident("no_main"));
    file.attrs.push(syn::parse_quote!(#![no_main]));
    file.items
        .insert(0, syn::parse_quote!(sp1_zkvm::entrypoint!(#entry);));
    file.items.push(syn::parse_quote! {
        pub fn #entry() {
            #(#input_reads)*
            let result = #computation;
            sp1_zkvm::io::commit(&result);
        }
    });
    Ok(format!("//! SP1 guest generated by py2zkvm.\n//! Transpiled functions retain their original Rust error handling.\n\n{}",
               prettyplease::unparse(&file)))
}

pub fn generate_host_code(config: &Sp1Config) -> Result<String> {
    let main_fn = &config.main_function;

    let input_writes: Vec<String> = main_fn
        .params
        .iter()
        .map(|(name, typ)| -> Result<String> {
            let simplified_type = parser::format_type(&parser::input_type_for_zkvm(typ)?);
            let example_value = get_example_value_with_name(&simplified_type, name);
            Ok(format!(
                "    // Input: {} (type: {})\n    let {}: {} = {};\n    stdin.write(&{});",
                name, simplified_type, name, simplified_type, example_value, name
            ))
        })
        .collect::<Result<_>>()?;

    let output_type = parser::format_type(&parser::output_type_for_zkvm(&main_fn.return_type)?);

    Ok(format!(
        r#"//! SP1 Host Program - Generated by py2zkvm
//! Executes the guest program and generates/verifies proofs

use sp1_sdk::{{include_elf, ProverClient, SP1Stdin}};
use std::time::Instant;

/// The ELF binary of the guest program (loaded via sp1-build)
pub const GUEST_ELF: &[u8] = include_elf!("program");

fn main() {{
    // Initialize SP1 logging
    sp1_sdk::utils::setup_logger();

    // Initialize the prover client
    let client = ProverClient::new();

    // Setup the proving and verifying keys
    let (pk, vk) = client.setup(GUEST_ELF);

    // Prepare inputs
    let mut stdin = SP1Stdin::new();

{input_writes}

    println!("Generating proof...");
    let prove_start = Instant::now();

    // Generate the proof
    let mut proof = client
        .prove(&pk, stdin)
        .run()
        .expect("proof generation failed");
    let prove_elapsed = prove_start.elapsed();
    println!("Proof generated in {{:?}}", prove_elapsed);

    // Read the public output
    let result: {output_type} = proof.public_values.read();
    println!("Computation result: {{:?}}", result);

    // Verify the proof
    let verify_start = Instant::now();
    client.verify(&proof, &vk).expect("verification failed");
    let verify_elapsed = verify_start.elapsed();
    println!("Proof verified successfully in {{:?}}", verify_elapsed);

    // Save the proof
    let proof_bytes = bincode::serialize(&proof).expect("failed to serialize proof");
    std::fs::write("proof.bin", proof_bytes).expect("failed to save proof");
    println!("Proof saved to proof.bin");
}}
"#,
        input_writes = input_writes.join("\n\n"),
        output_type = output_type,
    ))
}

pub fn generate_lib_code(config: &Sp1Config) -> Result<String> {
    let main_fn = &config.main_function;

    let input_fields: Vec<String> = main_fn
        .params
        .iter()
        .map(|(name, typ)| -> Result<String> {
            let simplified_type = parser::format_type(&parser::input_type_for_zkvm(typ)?);
            Ok(format!("    pub {}: {},", name, simplified_type))
        })
        .collect::<Result<_>>()?;

    let output_type = parser::format_type(&parser::output_type_for_zkvm(&main_fn.return_type)?);

    Ok(format!(
        r#"//! Common types for the SP1 program
//! Generated by py2zkvm

use serde::{{Deserialize, Serialize}};

/// Input to the provable computation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Input {{
{input_fields}
}}

/// Output type alias
pub type Output = {output_type};
"#,
        input_fields = input_fields.join("\n"),
        output_type = output_type,
    ))
}

fn get_example_value_with_name(rust_type: &str, param_name: &str) -> String {
    let typ = rust_type.trim();
    let name = param_name.to_lowercase();

    match name.as_str() {
        "n" if typ.starts_with('i') || typ.starts_with('u') => "15".to_string(),
        "p" if typ.starts_with('i') || typ.starts_with('u') => "3".to_string(),
        "q" if typ.starts_with('i') || typ.starts_with('u') => "5".to_string(),
        _ => get_example_value(typ),
    }
}

fn get_example_value(rust_type: &str) -> String {
    let typ = rust_type.trim();

    match typ {
        "i8" | "i16" | "i32" | "i64" | "i128" | "isize" => "10".to_string(),
        "u8" | "u16" | "u32" | "u64" | "u128" | "usize" => "10".to_string(),
        "f32" | "f64" => "3.14".to_string(),
        "bool" => "true".to_string(),
        "()" => "()".to_string(),
        "String" => "\"example\".to_string()".to_string(),
        "&str" | "& str" => "\"example\"".to_string(),
        _ if typ.starts_with("Vec<") => {
            let inner = &typ[4..typ.len() - 1];
            let inner_example = get_example_value(inner);
            format!("vec![{}]", inner_example)
        }
        _ if typ.starts_with("Option<") => {
            let inner = &typ[7..typ.len() - 1];
            let inner_example = get_example_value(inner);
            format!("Some({})", inner_example)
        }
        _ if typ.starts_with('[') && typ.contains(';') => {
            let parts: Vec<&str> = typ[1..typ.len() - 1].split(';').collect();
            if parts.len() == 2 {
                let inner_type = parts[0].trim();
                let size: usize = parts[1].trim().parse().unwrap_or(1);
                let inner_example = get_example_value(inner_type);
                let values = vec![inner_example; size].join(", ");
                format!("[{}]", values)
            } else {
                "Default::default()".to_string()
            }
        }
        _ if typ.starts_with('(') && typ.ends_with(')') => {
            let inner = &typ[1..typ.len() - 1];
            let parts: Vec<&str> = inner.split(',').collect();
            let values: Vec<String> = parts.iter().map(|p| get_example_value(p.trim())).collect();
            format!("({})", values.join(", "))
        }
        _ => "Default::default()".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_example_values() {
        assert_eq!(get_example_value("i32"), "10");
        assert_eq!(get_example_value("bool"), "true");
        assert_eq!(get_example_value("Vec<i32>"), "vec![10]");
    }

    fn configuration(source: &str, selected: &str) -> Sp1Config {
        let rust_code = crate::transpiler::clean_for_zkvm(source).unwrap();
        let functions = crate::parser::parse_rust_functions(&rust_code).unwrap();
        let main_function = functions
            .iter()
            .find(|f| f.name == selected)
            .unwrap()
            .clone();
        Sp1Config {
            main_function,
            all_functions: functions,
            rust_code,
            precompiles: false,
        }
    }

    #[test]
    fn regression_result_output_preserves_function_and_error_types() {
        let source = r#"
#[derive(Debug)] pub struct DomainError;
impl std::fmt::Display for DomainError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { write!(f, "domain error") }
}
impl std::error::Error for DomainError {}
pub fn solve() -> std::result::Result < (i64, Vec<i64>), Box < dyn std::error::Error > > {
    if false { return Err(Box::new(DomainError)); }
    Ok((5, vec![6]))
}
#[doc = "DEPYLER-1216: Auto-generated entry point"] pub fn main() -> Result<(), Box<dyn std::error::Error>> { Ok(()) }
"#;
        let config = configuration(source, "solve");
        let guest = generate_guest_code(&config).unwrap();
        let parsed = syn::parse_file(&guest).unwrap();
        assert!(!parsed
            .items
            .iter()
            .any(|item| matches!(item, syn::Item::Fn(f) if f.sig.ident == "main")));
        assert!(guest.contains("struct DomainError"));
        assert!(guest.contains("return Err(Box::new(DomainError))"));
        assert!(guest.contains("Ok((5, vec![6]))"));
        assert!(guest.contains("unwrap_or_else"));
        assert!(generate_host_code(&config)
            .unwrap()
            .contains("let result: (i64, Vec<i64>)"));
    }

    #[test]
    fn regression_business_main_and_entrypoint_name_collision() {
        let config = configuration(
            "pub fn main() -> i64 { 7 } fn __py2zkvm_entrypoint() {}",
            "main",
        );
        let guest = generate_guest_code(&config).unwrap();
        assert!(guest.contains("pub fn main() -> i64"));
        assert!(guest.contains("sp1_zkvm::entrypoint!(__py2zkvm_entrypoint_);"));
        assert!(guest.contains("let result = main();"));
    }

    #[test]
    fn regression_mixed_borrowed_and_owned_inputs_have_matching_wire_types() {
        let config = configuration("pub fn update(xs: &mut Vec<i64>, amount: i64, scale: &i64) -> i64 { xs.push(amount); xs[0] * scale }", "update");
        let guest = generate_guest_code(&config).unwrap();
        assert!(guest.contains("let mut xs: Vec<i64> = sp1_zkvm::io::read();"));
        assert!(guest.contains("update(&mut xs, amount, &scale)"));
        let host = generate_host_code(&config).unwrap();
        assert!(host.contains("let amount: i64 = 10;"));
        assert!(host.contains("let scale: i64 = 10;"));
    }

    #[test]
    fn regression_unit_result_and_literal_text_are_preserved() {
        let source = r###"pub fn done() -> Result < (), Box<dyn std::error::Error> > {
    let _text = r#"Ok(5) Result<T,E> fn main() { }"#;
    Ok(())
}"###;
        let config = configuration(source, "done");
        let guest = generate_guest_code(&config).unwrap();
        assert!(guest.contains("Ok(5) Result<T,E> fn main() { }"));
        assert!(guest.contains("Ok(())"));
        assert!(guest.contains("unwrap_or_else"));
        assert!(generate_host_code(&config)
            .unwrap()
            .contains("let result: ()"));
    }

    #[cfg(unix)]
    #[test]
    fn regression_generated_guest_compiles_and_preserves_success_and_failure() {
        use std::process::Command;
        let directory = tempfile::tempdir().unwrap();
        let root = directory.path();
        let stub = root.join("sp1_stub.rs");
        std::fs::write(
            &stub,
            r#"
#[macro_export]
macro_rules! entrypoint {
    ($entry:path) => {
        const _: fn() = $entry;
        pub fn __py2zkvm_test_entry() { $entry(); }
    };
}
pub mod io {
    pub fn read<T>() -> T { panic!("this fixture has no inputs") }
    pub fn commit<T: std::fmt::Debug>(value: &T) { println!("PUBLIC={:?}", value); }
}
"#,
        )
        .unwrap();
        let compile = |args: &[String]| {
            let output = Command::new("rustc")
                .arg("--edition=2021")
                .arg("-Awarnings")
                .args(args)
                .output()
                .unwrap();
            assert!(
                output.status.success(),
                "{}",
                String::from_utf8_lossy(&output.stderr)
            );
        };
        let stub_lib = root.join("libsp1_zkvm.rlib");
        compile(&[
            "--crate-name".into(),
            "sp1_zkvm".into(),
            "--crate-type=rlib".into(),
            stub.display().to_string(),
            "-o".into(),
            stub_lib.display().to_string(),
        ]);
        let cases = [
            (
                r#"pub fn compute() -> Result < (i64, Vec<i32>), Box<dyn std::error::Error> > { Ok((5, vec![6])) }
#[doc = "DEPYLER-1216: Auto-generated entry point"] pub fn main() -> Result<(), Box<dyn std::error::Error>> { Ok(()) }"#,
                "compute",
                Some("PUBLIC=(5, [6])"),
            ),
            (
                "pub fn compute() -> Result<i64, &'static str> { Err(\"expected failure\") }",
                "compute",
                None,
            ),
            (
                "pub fn main() -> i64 { 7 } fn __py2zkvm_entrypoint() {}",
                "main",
                Some("PUBLIC=7"),
            ),
        ];
        for (source, selected, expected) in cases {
            let guest = root.join("guest.rs");
            std::fs::write(
                &guest,
                generate_guest_code(&configuration(source, selected)).unwrap(),
            )
            .unwrap();
            let guest_lib = root.join("libgenerated_guest.rlib");
            compile(&[
                "--crate-name".into(),
                "generated_guest".into(),
                "--crate-type=rlib".into(),
                guest.display().to_string(),
                "--extern".into(),
                format!("sp1_zkvm={}", stub_lib.display()),
                "-o".into(),
                guest_lib.display().to_string(),
            ]);
            let driver = root.join("driver.rs");
            std::fs::write(
                &driver,
                "fn main() { generated_guest::__py2zkvm_test_entry(); }",
            )
            .unwrap();
            let executable = root.join("run");
            compile(&[
                driver.display().to_string(),
                "--extern".into(),
                format!("generated_guest={}", guest_lib.display()),
                "-L".into(),
                format!("dependency={}", root.display()),
                "-o".into(),
                executable.display().to_string(),
            ]);
            let output = Command::new(executable).output().unwrap();
            if let Some(expected) = expected {
                assert!(
                    output.status.success(),
                    "{}",
                    String::from_utf8_lossy(&output.stderr)
                );
                assert_eq!(String::from_utf8_lossy(&output.stdout).trim(), expected);
            } else {
                assert!(!output.status.success());
                assert!(
                    output.stdout.is_empty(),
                    "failed computation must not commit output"
                );
            }
        }
    }
}
